def build_charset_2048() -> list[int]:
    """256 × 8 bytes; index i+128 = inverted(i) for reverse-PETSCII."""
    buf = [0] * 2048
    # Map ASCII code (as Quattro writes to screen RAM) to glyph table.
    for code in range(128):
        ch = chr(code) if 32 <= code < 127 else None
        rows: list[int]
        if ch is not None and ch in GLYPHS:
            rows = GLYPHS[ch]
        else:
            rows = empty()
        base = code * 8
        for r in range(8):
            buf[base + r] = rows[r] & 0xFF
    for code in range(128, 256):
        src = (code - 128) * 8
        dst = code * 8
        for r in range(8):
            buf[dst + r] = (~buf[src + r]) & 0xFF
    return buf


def emit_c_header(buf: list[int]) -> None:
    assert len(buf) == 2048
    out = sys.stdout
    out.write(
        "/**\n"
        " * @file bank2_working_charset_data.h\n"
        " * @brief 2K VIC charset for Quattro bank-2 readable pass (B3). Generated; do not edit by hand.\n"
        " *\n"
        " * Source: `tools/c64/gen_bank2_working_charset.py`. Indices 128–255 are inverted 0–127\n"
        " * (reverse-PETSCII). Screen RAM uses ASCII-like codes (see `video.c`).\n"
        " */\n\n"
        "#ifndef QUATTRO_PLATFORM_C64_BANK2_WORKING_CHARSET_DATA_H\n"
        "#define QUATTRO_PLATFORM_C64_BANK2_WORKING_CHARSET_DATA_H\n\n"
        "static const unsigned char k_charset_embedded_bank2[2048] = {\n"
    )
    for i in range(0, 2048, 16):
        chunk = buf[i : i + 16]
        parts = ", ".join(f"0x{b:02X}" for b in chunk)
        tail = "," if i + 16 < 2048 else ""
        out.write(f"    {parts}{tail}\n")
    out.write("};\n\n")
    out.write(
        "_Static_assert(sizeof k_charset_embedded_bank2 == 2048u, "
        "\"bank2 working charset is 2K\");\n\n"
        "#endif /* QUATTRO_PLATFORM_C64_BANK2_WORKING_CHARSET_DATA_H */\n"
    )


def main() -> None:
    buf = build_charset_2048()
    emit_c_header(buf)


if __name__ == "__main__":
    main()
