def rows_from_bitmap(lines: list[str]) -> list[int]:
    """Eight strings of eight chars; '#' = foreground, '.' = background."""
    out: list[int] = []
    for line in lines:
        if len(line) != 8:
            raise ValueError(line)
        b = 0
        for i, ch in enumerate(line):
            if ch == "#":
                b |= 0x80 >> i
        out.append(b)
    return out


